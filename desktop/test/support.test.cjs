const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../../src/support.js'), 'utf8');

test('content reports work signed out, never upload data and offer a user-reviewed email plus clipboard fallback', async () => {
  const { Window } = await import('happy-dom');
  const w = new Window({ url: 'https://aurix-ea09b.web.app/#chat' });
  const d = w.document;
  let network = 0, copied;
  w.AurixDesktop = { signIn() {} };
  w.fetch = async () => { network++; throw Error('No network expected'); };
  Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async value => { copied = value; } }, configurable: true });
  w.eval(source);
  assert.equal(d.querySelector('#windows-privacy-link').hidden, false);
  assert.equal(d.querySelector('#windows-privacy-link').getAttribute('href'), '/pages/windows-privacy.html');
  d.querySelector('#report-content').click();
  const dialog = d.querySelector('#content-report');
  assert.equal(dialog.open, true);
  const submit = () => d.querySelector('#report-form').dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
  submit();
  assert.equal(d.querySelector('#report-email').hidden, true);
  d.querySelector('#report-details').value = 'The output contains harmful material. <script>unsafe</script>';
  w.localStorage.setItem('aurix_v1_user_secret_chat', 'PRIVATE PDF AND OUTPUT');
  submit();
  const email = new URL(d.querySelector('#report-email').href);
  assert.equal(email.protocol, 'mailto:');
  assert.equal(email.pathname, 'ahmedbecetti41@gmail.com');
  assert.match(email.searchParams.get('body'), /Area: chat/);
  assert.match(email.searchParams.get('body'), /harmful material/);
  assert.doesNotMatch(email.searchParams.get('body'), /PRIVATE PDF/);
  assert.equal(dialog.querySelector('script'), null);
  assert.match(d.querySelector('#report-status').textContent, /not sent/);
  d.querySelector('#report-copy').click();
  await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(copied, email.searchParams.get('body'));
  assert.equal(network, 0);
  w.location.hash = '#secret-token-should-not-leak';
  submit();
  assert.doesNotMatch(new URL(d.querySelector('#report-email').href).searchParams.get('body'), /secret-token/);
  d.querySelector('#report-close').click();
  assert.equal(dialog.open, false);
  d.documentElement.lang = 'ar';
  await new Promise(resolve => setTimeout(resolve, 10));
  assert.match(d.querySelector('#report-content').textContent, /الإبلاغ/);
  d.querySelector('#report-content').click();
  assert.match(d.querySelector('#report-title').textContent, /غير مناسب/);
  assert.equal(d.querySelector('#report-email').hasAttribute('href'), false);
  await w.happyDOM.abort();
});

test('public Windows privacy is bundled without authentication and discloses actual data flows', () => {
  const policy = fs.readFileSync(path.join(__dirname, '../../release/preview/pages/windows-privacy.html'), 'utf8');
  assert.match(policy, /Firebase Authentication/);
  assert.match(policy, /Pollinations/);
  assert.match(policy, /Gemini/);
  assert.match(policy, /MSIX/);
  assert.match(policy, /original PDF file is not uploaded/);
  assert.match(policy, /No report is transmitted until you send/);
  assert.match(policy, /ahmedbecetti41@gmail.com/);
  assert.doesNotMatch(policy, /<script/);
});
